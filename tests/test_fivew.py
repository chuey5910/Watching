import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from jabta.fivew import extract
from jabta.article_body import extract_body

# (หัวข้อ, เนื้อข่าว, ช่องที่ต้องจับได้ -> ค่าที่ต้องมีอยู่ในผล)
CASES = [
    ("ชาวบ้านบุกศาลากลาง",
     "เมื่อเวลา 09.00 น. วันที่ 24 กันยายน 2569 ที่ศาลากลางจังหวัดอุดรธานี "
     "นายสมชาย ใจดี แกนนำกลุ่มอนุรักษ์ นำชาวบ้านกว่า 300 คน รวมตัวยื่นหนังสือ",
     {"ใคร": "ใจดี", "ที่ไหน": "อุดรธานี", "เมื่อไหร่": "09.00"}),
    # ชื่อและจังหวัดที่ขึ้นต้นด้วยสระหน้า เคยจับไม่ได้เพราะ regex ใช้แค่ ก-ฮ
    ("ม็อบปิดถนนเชียงใหม่",
     "วันที่ 24 ก.ย. 2569 ที่จังหวัดเชียงใหม่ นางไพบูลย์ ศรีทอง นำผู้ชุมนุม 120 คน "
     "ปิดถนน เนื่องจากไม่พอใจการจัดสรรงบประมาณ",
     {"ใคร": "ไพบูลย์", "ที่ไหน": "เชียงใหม่", "ทำไม": "งบประมาณ"}),
    ("น้ำท่วมแพร่",
     "ที่อำเภอเด่นชัย จังหวัดแพร่ เกิดน้ำท่วมฉับพลัน หลังฝนตกหนักต่อเนื่องสามวัน "
     "โดยเจ้าหน้าที่เร่งอพยพชาวบ้าน 80 ครัวเรือน",
     {"ที่ไหน": "เด่นชัย", "อย่างไร": "อพยพ", "ทำไม": "ฝนตกหนัก"}),
]

HTML = """<html><head><meta charset="utf-8"></head><body>
<nav><a href="/">หน้าแรก</a></nav>
<div class="sidebar"><p>ดาราดังประกาศแต่งงานกลางงานอีเวนต์ใหญ่ที่โรงแรมหรูใจกลางเมือง</p></div>
<article><p>เมื่อเวลา 09.00 น. ที่จังหวัดอุดรธานี ชาวบ้านรวมตัวยื่นหนังสือต่อผู้ว่าราชการจังหวัด</p>
<p>อ่านข่าวที่เกี่ยวข้อง</p>
<p>ย้อนรอยโครงการเหมืองโปแตช 20 ปีแห่งการคัดค้านของชาวบ้านในพื้นที่จังหวัดอุดรธานี</p></article>
<footer><p>สงวนลิขสิทธิ์ 2569 สำนักข่าวตัวอย่าง ติดต่อโฆษณาได้ที่เบอร์ 02-000-0000</p></footer>
</body></html>"""


def run():
    bad = 0
    for title, body, want in CASES:
        got = extract(title, body)
        for field, needle in want.items():
            if needle not in (got.get(field) or ""):
                bad += 1
                print(f"  ผิด  [{field}] ต้องมี '{needle}' แต่ได้ '{got.get(field)}' | {title}")
    text = extract_body(HTML)
    for junk in ("ดาราดัง", "ย้อนรอยโครงการ", "สงวนลิขสิทธิ์"):
        if junk in text:
            bad += 1
            print(f"  ผิด  ตัวดึงเนื้อข่าวปล่อย '{junk}' หลุดเข้ามา")
    if "ยื่นหนังสือ" not in text:
        bad += 1
        print("  ผิด  ตัวดึงเนื้อข่าวไม่ได้เนื้อหาจริง")
    total = sum(len(w) for _, _, w in CASES) + 4
    print(f"ผ่าน {total - bad}/{total}" + ("  ผ่านหมด" if not bad else f"  ตก {bad}"))
    return bad


if __name__ == "__main__":
    sys.exit(1 if run() else 0)
